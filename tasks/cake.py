"""
Программа проверяет, какое количество пирожных
можно расфасовать по коробкам на 3 или 5 штук.
"""

def print_pack_report(number):
    """
    Выводит отчёт о фасовке пирожных
    от заданного количества до 1.

    number — начальное количество пирожных.
    """
    for i in range(number, 0, -1):
        if i % 3 == 0 and i % 5 == 0:
            print(i, "- расфасуем по 3 или по 5")
        elif i % 5 == 0:
            print(i, "- расфасуем по 5")
        elif i % 3 == 0:
            print(i, "- расфасуем по 3")
        else:
            print(i, "- не заказываем!")

print_pack_report(10)
